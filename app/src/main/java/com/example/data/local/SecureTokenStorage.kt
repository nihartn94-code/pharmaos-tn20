package com.example.data.local

import android.content.Context
import android.content.SharedPreferences
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import androidx.annotation.VisibleForTesting
import java.security.KeyStore
import java.security.SecureRandom
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import javax.crypto.spec.SecretKeySpec

/**
 * Thrown when Android Keystore encryption/key generation fails in production.
 * Production token storage fails closed and NEVER falls back to an ephemeral in-memory key
 * or plaintext persistence.
 */
class SecureTokenStorageException(
    message: String,
    cause: Throwable? = null
) : SecurityException(message, cause)

/**
 * Abstraction over AES-256-GCM token encryption so production builds strictly use
 * [AndroidKeystoreTokenCipher] while JVM/Robolectric unit tests can explicitly inject
 * [InMemoryTestTokenCipher] without weakening production security.
 */
interface TokenCipher {
    fun encrypt(plaintext: String): String
    fun decrypt(encoded: String): String
}

/**
 * Production-only cipher backed exclusively by hardware/OS `AndroidKeyStore` (AES-256-GCM).
 *
 * Security invariants:
 * - Never exports the master key from Android Keystore.
 * - Never falls back to an ephemeral in-memory key or plaintext.
 * - Uses randomized 12-byte GCM IVs generated by Android Keystore on every encryption call.
 */
class AndroidKeystoreTokenCipher(
    private val keyAlias: String = DEFAULT_KEY_ALIAS
) : TokenCipher {

    companion object {
        const val DEFAULT_KEY_ALIAS = "pharmaos_jwt_master_key_v1"
        private const val KEYSTORE_PROVIDER = "AndroidKeyStore"
        private const val AES_GCM_TRANSFORMATION = "AES/GCM/NoPadding"
        private const val GCM_TAG_BITS = 128
        private const val GCM_IV_BYTES = 12
    }

    private fun getOrCreateKeystoreSecretKey(): SecretKey {
        return try {
            val keyStore = KeyStore.getInstance(KEYSTORE_PROVIDER).apply { load(null) }
            val existing = keyStore.getKey(keyAlias, null) as? SecretKey
            if (existing != null) {
                existing
            } else {
                val keyGenerator = KeyGenerator.getInstance(
                    KeyProperties.KEY_ALGORITHM_AES,
                    KEYSTORE_PROVIDER
                )
                val spec = KeyGenParameterSpec.Builder(
                    keyAlias,
                    KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
                )
                    .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                    .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                    .setKeySize(256)
                    .setRandomizedEncryptionRequired(true)
                    .build()
                keyGenerator.init(spec)
                keyGenerator.generateKey()
            }
        } catch (t: Throwable) {
            throw SecureTokenStorageException(
                "Android Keystore is unavailable or failed to initialize the JWT encryption key.",
                t
            )
        }
    }

    override fun encrypt(plaintext: String): String {
        return try {
            val secretKey = getOrCreateKeystoreSecretKey()
            val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION)
            cipher.init(Cipher.ENCRYPT_MODE, secretKey)
            val iv = cipher.iv
            val ciphertext = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))
            val combined = ByteArray(1 + iv.size + ciphertext.size)
            combined[0] = iv.size.toByte()
            System.arraycopy(iv, 0, combined, 1, iv.size)
            System.arraycopy(ciphertext, 0, combined, 1 + iv.size, ciphertext.size)
            Base64.encodeToString(combined, Base64.NO_WRAP)
        } catch (e: SecureTokenStorageException) {
            throw e
        } catch (t: Throwable) {
            throw SecureTokenStorageException("Failed to encrypt authentication token with Android Keystore.", t)
        }
    }

    override fun decrypt(encoded: String): String {
        return try {
            val combined = Base64.decode(encoded, Base64.NO_WRAP)
            if (combined.size <= 1 + GCM_IV_BYTES) {
                throw SecureTokenStorageException("Encrypted token payload is truncated or malformed.")
            }
            val ivLen = combined[0].toInt() and 0xFF
            if (ivLen <= 0 || combined.size <= 1 + ivLen) {
                throw SecureTokenStorageException("Encrypted token IV length is invalid.")
            }
            val iv = combined.copyOfRange(1, 1 + ivLen)
            val ciphertext = combined.copyOfRange(1 + ivLen, combined.size)
            val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION)
            cipher.init(Cipher.DECRYPT_MODE, getOrCreateKeystoreSecretKey(), GCMParameterSpec(GCM_TAG_BITS, iv))
            String(cipher.doFinal(ciphertext), Charsets.UTF_8)
        } catch (e: SecureTokenStorageException) {
            throw e
        } catch (t: Throwable) {
            throw SecureTokenStorageException("Failed to decrypt authentication token with Android Keystore.", t)
        }
    }
}

/**
 * Explicitly injected AES-256-GCM test cipher for JVM/Robolectric unit tests where
 * `AndroidKeyStore` is unavailable. NEVER wired as a default or fallback in production code.
 */
@VisibleForTesting
class InMemoryTestTokenCipher : TokenCipher {
    companion object {
        private const val AES_GCM_TRANSFORMATION = "AES/GCM/NoPadding"
        private const val GCM_TAG_BITS = 128
        private const val GCM_IV_BYTES = 12
    }

    private val secureRandom = SecureRandom()
    private val secretKey: SecretKey = ByteArray(32).also { secureRandom.nextBytes(it) }
        .let { SecretKeySpec(it, "AES") }

    override fun encrypt(plaintext: String): String {
        val iv = ByteArray(GCM_IV_BYTES).also { secureRandom.nextBytes(it) }
        val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey, GCMParameterSpec(GCM_TAG_BITS, iv))
        val ciphertext = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))
        val combined = ByteArray(1 + iv.size + ciphertext.size)
        combined[0] = iv.size.toByte()
        System.arraycopy(iv, 0, combined, 1, iv.size)
        System.arraycopy(ciphertext, 0, combined, 1 + iv.size, ciphertext.size)
        return Base64.encodeToString(combined, Base64.NO_WRAP)
    }

    override fun decrypt(encoded: String): String {
        val combined = Base64.decode(encoded, Base64.NO_WRAP)
        if (combined.size <= 1 + GCM_IV_BYTES) {
            throw SecureTokenStorageException("Invalid test ciphertext.")
        }
        val ivLen = combined[0].toInt() and 0xFF
        val iv = combined.copyOfRange(1, 1 + ivLen)
        val ciphertext = combined.copyOfRange(1 + ivLen, combined.size)
        val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, secretKey, GCMParameterSpec(GCM_TAG_BITS, iv))
        return String(cipher.doFinal(ciphertext), Charsets.UTF_8)
    }
}

/**
 * Android Keystore-backed AES-256-GCM encrypted token storage for JWT access & refresh tokens.
 *
 * Security properties:
 * - Production uses [AndroidKeystoreTokenCipher] exclusively (zero ephemeral fallback).
 * - Dedicated SharedPreferences file (`pharmaos_secure_tokens.xml`) explicitly excluded from
 *   Android Auto Backup and Device Transfer in `backup_rules.xml` and `data_extraction_rules.xml`.
 * - Corrupt or invalidated ciphertext fails closed (scrubbed from preferences and returns `null`).
 * - Never logs access tokens, refresh tokens, or ciphertext.
 */
class SecureTokenStorage(
    context: Context,
    prefsFileName: String = SECURE_PREFS_FILE_NAME,
    private val cipher: TokenCipher = AndroidKeystoreTokenCipher()
) {
    companion object {
        const val SECURE_PREFS_FILE_NAME = "pharmaos_secure_tokens"
        private const val PREF_ACCESS_TOKEN_ENC = "enc_access_token_v1"
        private const val PREF_REFRESH_TOKEN_ENC = "enc_refresh_token_v1"

        @VisibleForTesting
        fun createForUnitTest(
            context: Context,
            prefsFileName: String = SECURE_PREFS_FILE_NAME,
            cipher: TokenCipher = InMemoryTestTokenCipher()
        ): SecureTokenStorage = SecureTokenStorage(
            context = context,
            prefsFileName = prefsFileName,
            cipher = cipher
        )
    }

    private val prefs: SharedPreferences =
        context.applicationContext.getSharedPreferences(prefsFileName, Context.MODE_PRIVATE)

    private val lock = Any()

    fun getAccessToken(): String? = synchronized(lock) {
        val encoded = prefs.getString(PREF_ACCESS_TOKEN_ENC, null) ?: return null
        decryptOrScrub(PREF_ACCESS_TOKEN_ENC, encoded)
    }

    fun getRefreshToken(): String? = synchronized(lock) {
        val encoded = prefs.getString(PREF_REFRESH_TOKEN_ENC, null) ?: return null
        decryptOrScrub(PREF_REFRESH_TOKEN_ENC, encoded)
    }

    fun saveTokens(accessToken: String?, refreshToken: String?) = synchronized(lock) {
        val editor = prefs.edit()
        if (!accessToken.isNullOrBlank()) {
            editor.putString(PREF_ACCESS_TOKEN_ENC, cipher.encrypt(accessToken))
        } else {
            editor.remove(PREF_ACCESS_TOKEN_ENC)
        }
        if (!refreshToken.isNullOrBlank()) {
            editor.putString(PREF_REFRESH_TOKEN_ENC, cipher.encrypt(refreshToken))
        } else if (accessToken.isNullOrBlank()) {
            editor.remove(PREF_REFRESH_TOKEN_ENC)
        }
        editor.commit()
    }

    fun clearTokens() = synchronized(lock) {
        prefs.edit()
            .remove(PREF_ACCESS_TOKEN_ENC)
            .remove(PREF_REFRESH_TOKEN_ENC)
            .commit()
    }

    fun hasEncryptedTokens(): Boolean = synchronized(lock) {
        prefs.contains(PREF_ACCESS_TOKEN_ENC) || prefs.contains(PREF_REFRESH_TOKEN_ENC)
    }

    private fun decryptOrScrub(prefKey: String, encoded: String): String? {
        if (encoded.isBlank()) return null
        return try {
            cipher.decrypt(encoded).takeIf { it.isNotBlank() }
        } catch (_: Throwable) {
            // Fail closed on corrupted ciphertext or invalidated Keystore key; scrub unreadable entry.
            prefs.edit().remove(prefKey).commit()
            null
        }
    }
}
